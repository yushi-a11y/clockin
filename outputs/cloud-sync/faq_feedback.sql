-- ============================================================
-- faq_feedback：记录自助答疑未匹配或低置信度的问题
-- 供管理员定期 review 并扩充 FAQ 知识库
-- ============================================================

create table if not exists public.faq_feedback (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  ts bigint not null,                       -- 前端/机器人提交时的毫秒时间戳
  question text not null,                   -- 用户原始问题
  role text not null default 'employee',    -- 提问者角色：employee / admin / dingtalk-bot
  source text not null default 'help-center', -- 来源：help-center / dingtalk-bot
  member jsonb default null,                -- { id?, name?, staffId? }
  handled boolean not null default false,   -- 管理员是否已处理
  notes text default null                   -- 管理员备注（补充到哪个 FAQ）
);

-- 安全策略：允许已认证用户插入自己的反馈；service_role 可全部读写
-- 注意：Edge Function 使用 service_role 写入，不受 RLS 限制。
alter table public.faq_feedback enable row level security;

drop policy if exists faq_feedback_insert_authenticated on public.faq_feedback;
create policy faq_feedback_insert_authenticated
  on public.faq_feedback
  for insert
  to authenticated
  with check (role = 'employee');

drop policy if exists faq_feedback_select_admin on public.faq_feedback;
create policy faq_feedback_select_admin
  on public.faq_feedback
  for select
  to authenticated
  using (auth.role() = 'authenticated');

-- 索引：按处理状态和时间倒序查看
create index if not exists faq_feedback_handled_created_idx
  on public.faq_feedback (handled, created_at desc);
